"""Generate lazy-package typing stubs from the runtime export declarations.

Run with the repository's development environment so formatting uses the pinned
Ruff version. Only declaration files and the lazy-export helper are loaded;
exported implementations and optional dependencies are never imported.
"""

from __future__ import annotations

import argparse
import json
import runpy
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory


def render_stub(exports: dict[str, tuple[str, str]], wildcard_names: list[str]) -> str:
    """Keep explicit re-exports and the runtime's wildcard surface distinct."""

    lines = [
        '"""Generated by scripts/generate_public_api_stubs.py; do not edit."""',
        "",
    ]
    for name, (module, symbol) in sorted(exports.items()):
        lines.append(f"from {module} import {symbol} as {name}")
    implicit_wildcard = {name for name in exports if not name.startswith("_")}
    if set(wildcard_names) != implicit_wildcard:
        lines.extend(["", "__all__ = ["])
        lines.extend(f"    {name!r}," for name in sorted(wildcard_names))
        lines.append("]")
    return "\n".join(lines) + "\n"


def generated_stubs(root: Path) -> dict[Path, str]:
    """Render every declared lazy package without importing Cayu implementations."""

    packages = json.loads((root / "docs/public-api-packages.json").read_text(encoding="utf-8"))
    if (
        not isinstance(packages, list)
        or not packages
        or not all(isinstance(name, str) for name in packages)
    ):
        raise ValueError("public-api-packages.json must contain a nonempty list of package names")
    if len(packages) != len(set(packages)):
        raise ValueError("public-api-packages.json contains duplicate packages")
    declarations = {root / "src" / Path(*name.split(".")) / "_exports.py" for name in packages}
    discovered = set((root / "src/cayu").rglob("_exports.py"))
    if declarations != discovered:
        missing = sorted(str(path.relative_to(root)) for path in declarations - discovered)
        unlisted = sorted(str(path.relative_to(root)) for path in discovered - declarations)
        raise ValueError(
            f"public package inventory differs: missing={missing}, unlisted={unlisted}"
        )

    wildcard_names = runpy.run_path(str(root / "src/cayu/_api.py"))["wildcard_names"]
    rendered: dict[Path, str] = {}
    for path in sorted(declarations):
        manifest = runpy.run_path(str(path))
        exports = manifest["EXPORTS"]
        public_names = manifest["PUBLIC_NAMES"]
        if len(public_names) != len(set(public_names)) or not set(public_names) <= set(exports):
            raise ValueError(f"{path.relative_to(root)} has invalid PUBLIC_NAMES")
        rendered[path.with_name("__init__.pyi").relative_to(root)] = render_stub(
            exports, wildcard_names(public_names, exports)
        )

    # Format all files together, in isolation. Check mode never rewrites a stub,
    # and formatting failures cannot leave partially generated repository files.
    with TemporaryDirectory(prefix="cayu-public-api-stubs-") as temporary:
        staging = Path(temporary)
        for relative_path, source in rendered.items():
            target = staging / relative_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(source, encoding="utf-8", newline="\n")
        paths = [str(staging / path) for path in rendered]
        config = ["--config", str(root / "pyproject.toml")]
        for operation in (["check", "--select", "I,RUF022", "--fix"], ["format"]):
            subprocess.run(
                [sys.executable, "-m", "ruff", *operation, *config, *paths],
                check=True,
                capture_output=True,
                text=True,
                timeout=60,
            )
        return {path: (staging / path).read_text(encoding="utf-8") for path in rendered}


def generate(root: Path, *, check: bool) -> int:
    """Check or write the complete generated surface; return a CLI exit status."""

    generated = generated_stubs(root.resolve())
    changed = [
        path
        for path, source in generated.items()
        if not (root / path).is_file() or (root / path).read_bytes() != source.encode("utf-8")
    ]
    if check:
        if changed:
            print(
                "Public API stubs are stale. Run: uv run python scripts/generate_public_api_stubs.py"
            )
            for path in changed:
                print(path.as_posix())
            return 1
        print(f"All {len(generated)} public API stubs are current.")
        return 0
    for path in changed:
        (root / path).write_text(generated[path], encoding="utf-8", newline="\n")
        print(f"Updated {path.as_posix()}")
    print(f"Generated {len(generated)} public API stubs; {len(changed)} changed.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on drift without writing files")
    args = parser.parse_args()
    try:
        return generate(Path(__file__).resolve().parents[1], check=args.check)
    except (ValueError, OSError, subprocess.SubprocessError) as exc:
        print(str(exc), file=sys.stderr)
        if isinstance(exc, subprocess.CalledProcessError):
            print(exc.stderr, file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
