def collision_safe_json_object(
    items: Iterable[tuple[str, Any]],
    *,
    preserve_input_order: bool,
) -> dict[str, Any]:
    """Build a deterministic JSON object without dropping transformed key collisions."""

    indexed_items = [
        (
            index,
            key,
            json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False),
            value,
        )
        for index, (key, value) in enumerate(items)
    ]
    assigned: list[tuple[int, str, Any]] = []
    counts: dict[str, int] = {}
    used_keys: set[str] = set()
    for index, key, _, value in sorted(indexed_items, key=lambda item: (item[1], item[2])):
        count = counts.get(key, 0) + 1
        candidate = key if count == 1 else f"{key}_{count}"
        while candidate in used_keys:
            count += 1
            candidate = f"{key}_{count}"
        counts[key] = count
        used_keys.add(candidate)
        assigned.append((index, candidate, value))

    if preserve_input_order:
        assigned.sort(key=lambda item: item[0])
    return {key: value for _, key, value in assigned}


def _copy_durable_json_value(
    value: Any,
    field_name: str,
    *,
    path: str,
    active_container_ids: set[int],
    container_depth: int,
) -> Any:
    if value is None or type(value) is bool:
        return value
    if type(value) is str:
        return _require_durable_text(value, field_name, path=path)
    if type(value) is int:
        if MIN_DURABLE_JSON_INTEGER <= value <= MAX_DURABLE_JSON_INTEGER:
            return value
        raise DurableValueError("integer_out_of_range", field_name, path=path)
    if type(value) is float:
        if not isfinite(value):
            raise DurableValueError("non_finite_number", field_name, path=path)
        if value.is_integer() and not (
            MIN_DURABLE_JSON_INTEGER <= value <= MAX_DURABLE_JSON_INTEGER
        ):
            # JSONB can render an exponent-form integral float as an integer.
            # Reject values that would then fail the shared int64 contract on
            # reload instead of accepting a write that cannot be reconstructed.
            raise DurableValueError("integral_float_out_of_range", field_name, path=path)
        # JSON has one number domain rather than distinct integer/float types.
        # PostgreSQL JSONB may decode exponent-form integral floats (for
        # example, 1e18) as ``int`` while memory and SQLite otherwise retain a
        # Python ``float``. Canonicalize every in-range integral float at the
        # shared boundary so all stores, JSONL, hashing, and replay return the
        # exact same Python representation. This also collapses signed zero.
        return int(value) if value.is_integer() else value
    if type(value) in {list, FrozenJsonList}:
        next_depth = container_depth + 1
        if next_depth > MAX_DURABLE_JSON_NESTING:
            raise DurableValueError("nesting_too_deep", field_name, path=path)
        value_id = id(value)
        if value_id in active_container_ids:
            raise DurableValueError("circular_reference", field_name, path=path)
        active_container_ids.add(value_id)
        try:
            return [
                _copy_durable_json_value(
                    item,
                    field_name,
                    path=_durable_child_path(path, index, object_value=False),
                    active_container_ids=active_container_ids,
                    container_depth=next_depth,
                )
                for index, item in enumerate(value)
            ]
        finally:
            active_container_ids.remove(value_id)
    if type(value) in {dict, FrozenJsonDict}:
        next_depth = container_depth + 1
        if next_depth > MAX_DURABLE_JSON_NESTING:
            raise DurableValueError("nesting_too_deep", field_name, path=path)
        value_id = id(value)
        if value_id in active_container_ids:
            raise DurableValueError("circular_reference", field_name, path=path)
        active_container_ids.add(value_id)
        try:
            copied: dict[str, Any] = {}
            for index, (key, item) in enumerate(value.items()):
                child_path = _durable_child_path(path, index, object_value=True)
                if type(key) is not str:
                    raise DurableValueError(
                        "invalid_json_key",
                        field_name,
                        path=f"{child_path}/key",
                    )
                _require_durable_text(key, field_name, path=f"{child_path}/key")
                copied[key] = _copy_durable_json_value(
                    item,
                    field_name,
                    path=child_path,
                    active_container_ids=active_container_ids,
                    container_depth=next_depth,
                )
            return copied
        finally:
            active_container_ids.remove(value_id)
    raise DurableValueError("invalid_json_type", field_name, path=path)


def _canonical_durable_json_text(value: Any) -> str:
    if value is None:
        return "null"
    if type(value) is bool:
        return "true" if value else "false"
    if type(value) is str:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    if type(value) is int:
        return str(value)
    if type(value) is float:
        if value == 0.0:
            return "0"
        if value.is_integer():
            return str(int(value))
        sign, digits, decimal_exponent = Decimal(repr(value)).as_tuple()
        if type(decimal_exponent) is not int:  # pragma: no cover - finite float invariant
            raise AssertionError("Finite float produced a non-finite Decimal exponent.")
        exponent = decimal_exponent
        while len(digits) > 1 and digits[-1] == 0:
            digits = digits[:-1]
            exponent += 1
        coefficient = "".join(str(digit) for digit in digits)
        prefix = "-" if sign else ""
        return f"{prefix}{coefficient}e{exponent}"
    if type(value) is list:
        return "[" + ",".join(_canonical_durable_json_text(item) for item in value) + "]"
    if type(value) is dict:
        entries = (
            json.dumps(key, ensure_ascii=False, separators=(",", ":"))
            + ":"
            + _canonical_durable_json_text(value[key])
            for key in sorted(value)
        )
        return "{" + ",".join(entries) + "}"
    raise TypeError("Canonical durable JSON received an unvalidated value.")


def _copy_json_value(value: Any, field_name: str, seen: set[int]) -> Any:
    if value is None or type(value) in {str, bool, int}:
        return value
    if type(value) is float:
        if isfinite(value):
            return value
        raise ValueError(f"`{field_name}` must contain finite JSON numbers.")
    if type(value) in {list, FrozenJsonList}:
        value_id = id(value)
        if value_id in seen:
            raise ValueError(f"`{field_name}` must not contain circular references.")
        seen.add(value_id)
        try:
            return [
                _copy_json_value(item, f"{field_name}[{index}]", seen)
                for index, item in enumerate(value)
            ]
        finally:
            seen.remove(value_id)
    if type(value) in {dict, FrozenJsonDict}:
        value_id = id(value)
        if value_id in seen:
            raise ValueError(f"`{field_name}` must not contain circular references.")
        seen.add(value_id)
        try:
            copied: dict[str, Any] = {}
            for key, item in value.items():
                if type(key) is not str:
                    raise ValueError(f"`{field_name}` JSON object keys must be strings.")
                copied[key] = _copy_json_value(item, f"{field_name}.{key}", seen)
            return copied
        finally:
            seen.remove(value_id)
    raise ValueError(f"`{field_name}` must contain JSON-compatible values.")


def _durable_child_path(path: str, index: int, *, object_value: bool) -> str:
    marker = f"#{index}" if object_value else str(index)
    return _bounded_ascii_label(
        f"{path}/{marker}",
        limit=_MAX_DURABLE_ERROR_PATH_CHARS,
        fallback="$",
    )
